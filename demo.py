"""End-to-end demo without hardware.

    python demo.py              # runs on the recording in data/sample/
    python demo.py --synthetic  # runs on a generated signal (not a measurement)

Both write results/metrics.json and results/signal.png.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from evaluation.evaluate import main as evaluate_main
from processing.synthetic import synthetic_recording

SAMPLE_DIR = Path(__file__).parent / "data" / "sample"


def write_synthetic_csv(path: Path) -> None:
    """Write a synthetic signal in the same CSV format as acquisition/logger.py."""
    rec = synthetic_recording()
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w") as f:
        f.write("# SYNTHETIC signal generated by processing/synthetic.py, not a measurement\n")
        f.write("host_time_s,board_time_us,value,cue\n")
        for t, v, c in zip(rec.t, rec.value, rec.cue):
            f.write(f"{t:.6f},{int(round(t * 1e6))},{int(v)},{int(c)}\n")


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--synthetic", action="store_true")
    args = p.parse_args()

    if args.synthetic:
        print("*** SYNTHETIC SIGNAL: these numbers only show the pipeline runs; they are not results. ***")
        csv = Path("results/synthetic.csv")
        write_synthetic_csv(csv)
        return evaluate_main(["--test", str(csv), "--out", "results"])

    samples = sorted(SAMPLE_DIR.glob("*.csv"))
    if not samples:
        print(f"No recording in {SAMPLE_DIR} yet. Run `python demo.py --synthetic` to try the pipeline.")
        return 1
    return evaluate_main(["--test", *map(str, samples), "--out", "results"])


if __name__ == "__main__":
    sys.exit(main())
